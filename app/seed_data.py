# Dev/demo fixture (M2). Real titles, real page counts and real millimetre
# dimensions so the shelf maths and the size-variation views have something
# honest to work with.
#
# Deliberate choices, all of them here to exercise a specific feature:
#   * decimal `series_position` (1.5, 2.5, 0.5) for interquels and prequels —
#     SPEC §1/§13 says series numbers may have decimals;
#   * several physical formats including boxed_set, manga, dictionary,
#     oversized_folio, leather_bound, spiral_bound and board_book;
#   * every ownership_status and reading_state value appears at least once;
#   * one duplicate title in two formats (hardcover owned + paperback wanted),
#     which is what ownership-level dedup has to reason about (D3);
#   * multi-author rows, including a four-author one (Design Patterns);
#   * `isbn` is left NULL everywhere. Inventing ISBN-13s would hand M6's Open
#     Library lookups codes that resolve to the wrong book, which is worse than
#     no code. M6 ships its own ISBN fixture.
